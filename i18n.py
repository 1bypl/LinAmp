"""Proste tłumaczenia interfejsu LinAmp.

Polski jest językiem źródłowym — wszystkie napisy w kodzie są po polsku.
Funkcja :func:`tr` zwraca tłumaczenie dla aktualnie wybranego języka,
a jeśli go brakuje, po prostu zostawia polski tekst.

Wybór języka zapisujemy w ustawieniach. Zmiana języka wymaga ponownego
uruchomienia programu, dzięki czemu cały interfejs (łącznie z oknami
dialogowymi) od razu korzysta z właściwych napisów.
"""

from __future__ import annotations

from collections import OrderedDict

LANGUAGES: "OrderedDict[str, str]" = OrderedDict(
    (
        ("pl", "Polski"),
        ("en", "English"),
        ("de", "Deutsch"),
        ("fr", "Français"),
        ("es", "Español"),
        ("ru", "Русский"),
    )
)

_current = "pl"


def set_language(code: str) -> str:
    """Ustawia język interfejsu. Nieznany kod zastępujemy polskim."""
    global _current
    code = str(code or "pl").lower()
    _current = code if code in LANGUAGES else "pl"
    return _current


def language() -> str:
    return _current


def language_name(code: str | None = None) -> str:
    return LANGUAGES.get(code or _current, LANGUAGES["pl"])


def tr(text: str, **values) -> str:
    """Tłumaczy tekst i opcjonalnie uzupełnia pola ``{nazwa}``."""
    translated = _TRANSLATIONS.get(_current, {}).get(text, text)
    if values:
        try:
            return translated.format(**values)
        except (KeyError, ValueError):
            return translated
    return translated


def track_count(count: int) -> str:
    """Odmiana określenia „utwór” zgodnie z językiem interfejsu."""
    count = int(count)
    if _current == "pl":
        if count == 1:
            return "1 utwór"
        if count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
            return f"{count} utwory"
        return f"{count} utworów"
    if _current == "ru":
        if count % 10 == 1 and count % 100 != 11:
            word = "трек"
        elif count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
            word = "трека"
        else:
            word = "треков"
        return f"{count} {word}"
    if count == 1:
        return tr("{count} utwór", count=count)
    return tr("{count} utworów", count=count)


def station_count(count: int) -> str:
    """Odmiana określenia „stacja” w komunikatach radia."""
    count = int(count)
    if _current == "pl":
        if count == 1:
            return "1 stacja"
        if count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
            return f"{count} stacje"
        return f"{count} stacji"
    if _current == "ru":
        if count % 10 == 1 and count % 100 != 11:
            word = "станция"
        elif count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
            word = "станции"
        else:
            word = "станций"
        return f"{count} {word}"
    if count == 1:
        return tr("{count} stacja", count=count)
    return tr("{count} stacji", count=count)


